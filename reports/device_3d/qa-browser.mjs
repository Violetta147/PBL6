import { createRequire } from 'node:module';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
const require = createRequire(import.meta.url);
const pkg = process.env.PLAYWRIGHT_PACKAGE || 'C:/Users/LAPTOP T&T/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright';
const { chromium } = require(pkg);
const root = fileURLToPath(new URL('.', import.meta.url));
await mkdir(new URL('qa', import.meta.url), { recursive: true });
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true, args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR:', e.message); });
page.on('console', e => { if (e.type() === 'error') console.log('CONSOLE:', e.text()); });
const requests = []; page.on('request', r => requests.push(r.url()));
await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
try { await page.waitForFunction(() => window.deviceViewer?.ready); }
catch (e) { await page.screenshot({ path: path.join(root, 'qa', 'failure.png') }); await browser.close(); throw new Error(`${e.message}; ${errors.join('; ')}`); }
await page.waitForTimeout(900);
const initial = await page.evaluate(() => window.deviceViewer.inspect());
if (initial.visible.includes('fan') || initial.visible.includes('esp32')) throw Error('Optional components shown by default');
await page.screenshot({ path: path.join(root, 'preview.png'), fullPage: true });
await page.getByRole('button', { name: 'Tách cụm', exact: true }).click();
await page.waitForFunction(() => window.deviceViewer.state.explode > .995);
const exploded = await page.evaluate(() => window.deviceViewer.inspect());
if (exploded.visible.includes('wiring')) throw Error('Wires must be hidden when exploded');
await page.screenshot({ path: path.join(root, 'qa', 'exploded.png'), fullPage: true });
await page.selectOption('#partSelect', 'pi');
await page.getByRole('button', { name: 'Xem riêng', exact: true }).click();
const isolated = await page.evaluate(() => window.deviceViewer.inspect());
if (isolated.visible.join() !== 'pi') throw Error('Isolation failed');
await page.getByRole('button', { name: 'Hiện toàn bộ', exact: true }).click();
await page.getByRole('button', { name: 'Bên trong', exact: true }).click();
await page.waitForFunction(() => window.deviceViewer.state.explode < .005);
const inside = await page.evaluate(() => window.deviceViewer.inspect());
if (inside.visible.some(id => ['shell', 'front', 'rear'].includes(id))) throw Error('Inside mode still has enclosure');
await page.screenshot({ path: path.join(root, 'qa', 'inside.png'), fullPage: true });
await page.check('#espToggle'); await page.check('#fanToggle');
const options = await page.evaluate(() => window.deviceViewer.inspect());
if (!options.visible.includes('esp32') || !options.visible.includes('fan')) throw Error('Optional toggle failed');
await page.uncheck('#espToggle'); await page.uncheck('#fanToggle');
await page.getByRole('button', { name: 'Lắp ráp', exact: true }).click();
await page.locator('#rearView').click();
await page.screenshot({ path: path.join(root, 'qa', 'rear.png'), fullPage: true });
const hit = await page.evaluate(() => {
  const v = window.deviceViewer, lens = v.device.root.getObjectByName('lens_glass');
  v.camera.position.set(0, 205, 440); v.controls.target.set(0, 100, 0); v.controls.update(); v.camera.updateMatrixWorld(true); v.device.root.updateMatrixWorld(true);
  const pos = lens.position.clone(); lens.getWorldPosition(pos); pos.project(v.camera);
  const r = document.querySelector('canvas').getBoundingClientRect(); return { x: r.left + (pos.x * .5 + .5) * r.width, y: r.top + (-pos.y * .5 + .5) * r.height };
});
await page.mouse.click(hit.x, hit.y); const picked = await page.evaluate(() => window.deviceViewer.state.selected);
if (picked !== 'camera') throw Error(`3D picking selected ${picked}, expected camera`);
const exports = {};
for (const mode of process.env.SKIP_GLB ? [] : ['assembled', 'exploded']) {
  console.log(`Exporting ${mode} GLB`);
  const data = await page.evaluate(mode => window.deviceViewer.exportModel(mode, false), mode);
  const buffer = Buffer.from(data, 'base64'); await writeFile(path.join(root, `pbl6-device-${mode}.glb`), buffer);
  if (buffer.readUInt32LE(0) !== 0x46546c67 || buffer.readUInt32LE(4) !== 2) throw Error('Invalid GLB header');
  const length = buffer.readUInt32LE(12), json = JSON.parse(buffer.subarray(20, 20 + length).toString());
  if (!json.nodes.some(n => n.name === 'pi') || !json.nodes.some(n => n.name === 'display')) throw Error('GLB lost assembly names');
  if (json.nodes.some(n => n.name === 'esp32' || n.name === 'fan')) throw Error('Default GLB must omit optional assemblies');
  if (!json.nodes.some(n => n.scale?.every(s => Math.abs(s - .001) < .000001) || (n.matrix && [0, 5, 10].every(i => Math.abs(n.matrix[i] - .001) < .000001)))) throw Error('GLB must convert mm to meters');
  exports[mode] = { bytes: buffer.length, nodes: json.nodes.length, meshes: json.meshes.length, textures: json.textures?.length ?? 0 };
}
await page.locator('#resetView').click();
await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(350);
const phone = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, canvas: document.querySelector('canvas').getBoundingClientRect().width }));
if (phone.scroll > phone.width + 1) throw Error('Mobile horizontal overflow');
await page.screenshot({ path: path.join(root, 'qa', 'phone.png'), fullPage: true });
await page.setViewportSize({ width: 320, height: 760 }); await page.waitForTimeout(150);
const narrow = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
if (narrow.scroll > narrow.width + 1) throw Error('320px horizontal overflow');
if (errors.length) throw Error(errors.join('\n'));
if (requests.some(url => /^https?:/.test(url))) throw Error('Offline viewer makes external requests');
const result = { date: '2026-10-28', initial, exploded, isolated, inside, options, picked, exports, phone, narrow, errors, externalRequests: 0 };
await writeFile(path.join(root, 'qa', 'browser-results.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2)); await browser.close();
