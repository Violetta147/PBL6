"""Build a scoped Obsidian core-Slides CSS snippet with self-contained backgrounds.

Run from the repository root: python reports/build_obsidian_theme.py
Copy the resulting themes/dut/obsidian-slides.css into .obsidian/snippets/
as dut-stt-slides.css, then enable that snippet in Obsidian Appearance.
Only slide decks containing the dut-stt-marker element are affected.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'reports/themes/dut'


def data_url(name):
    return 'data:image/png;base64,' + base64.b64encode((ASSETS / name).read_bytes()).decode('ascii')


def main():
    scope = '.slides-container:has(.dut-stt-marker)'
    cover = scope + ':has(.slides > section:first-child.present)'
    css = f'''/* DUT backgrounds for this STT deck only. Generated by build_obsidian_theme.py.
   Images are embedded to avoid Obsidian/app:// relative-URL resolution issues. */
{scope} {{
  background-color: #fff;
  background-image: url("{data_url('content.png')}");
  background-size: cover;
  background-position: center;
}}
{cover} {{ background-image: url("{data_url('cover.png')}"); }}
{scope} .dut-stt-marker {{ display: none; }}
{scope} .reveal {{
  background: transparent;
  font-family: Arial, sans-serif;
  font-size: 30px;
  color: #14364e;
}}
{scope} .reveal .slides > section {{
  background: transparent;
  text-align: left;
  line-height: 1.4;
  padding: 20px 0 100px;
  box-sizing: border-box;
}}
{scope} .reveal h3 {{
  font-family: Arial, sans-serif;
  font-size: 1.3em;
  color: #075486;
  text-transform: none;
}}
{scope} .reveal a {{ color: #075486; }}
{scope} .reveal table {{ font-size: 0.9em; }}
{scope} .reveal th {{ color: #075486; }}
{scope} .reveal th, {scope} .reveal td {{ border-color: #b7c9d5; }}
{scope} .reveal img {{ margin: 10px 0; }}
{scope} .reveal .slides > section:first-child {{ padding-left: 180px; }}
{scope} .reveal .slides > section:first-child h3 {{ color: #ffe600; font-size: 1.6em; }}
{scope} .reveal .slides > section:first-child p {{ color: #fff; }}
'''
    (ASSETS / 'obsidian-slides.css').write_text(css, encoding='utf-8')
    print('Built scoped background snippet; no application settings changed by this script.')


if __name__ == '__main__':
    main()
